def validate_search_cfg(cfg: dict[str, Any]) -> None:
    search = cfg.get("search")
    if not isinstance(search, dict):
        raise ConfigError("Missing 'search' section (see configs/healing_search.yaml)")
    missing = [key for key in _REQUIRED if key not in search]
    if missing:
        raise ConfigError(f"search is missing keys: {', '.join(missing)}")
    if search["objective"] not in OBJECTIVES:
        raise ConfigError(f"search.objective must be one of {OBJECTIVES}")
    for key, spec in search["thresholds"].items():
        for field_name in ("step", "min_step", "min", "max"):
            if field_name not in spec:
                raise ConfigError(f"search.thresholds.{key} is missing '{field_name}'")
    learn_from = str((cfg.get("optimizer") or {}).get("learn_from", "model"))
    if learn_from not in LEARN_FROM:
        raise ConfigError(f"optimizer.learn_from must be one of {LEARN_FROM}")


def _failure_reason(item: AttackItem | None, category: str) -> str:
    """Plain-language reason a garak detector flagged this answer."""
    if item is None:
        return f"garak flagged the answer as unsafe ({category})"
    detectors = " ".join(item.detectors)
    triggers = item.notes.get("triggers") if isinstance(item.notes, dict) else None
    trigger = str(triggers[0])[:60] if isinstance(triggers, list) and triggers else ""
    if "AttackRogueString" in detectors:
        return (f"it obeyed an instruction injected into the task and printed '{trigger}'"
                if trigger else "it obeyed an instruction injected into the task")
    if "DecodeMatch" in detectors:
        return "it decoded hidden encoded text and repeated its payload"
    if "MitigationBypass" in detectors:
        return "it played along with the jailbreak instead of declining it"
    if "dan." in detectors:
        return "it answered in the jailbreak persona"
    if "ToxicComment" in detectors or "unsafe_content" in detectors:
        return "its answer was toxic (it continued offensive text)"
    return f"garak flagged the answer as unsafe ({category})"


@dataclass
class Candidate:
    moves: tuple[Move, ...]
    label: str
    cfg: dict[str, Any]
    result: EvalResult
    decision: Decision
    objective: float
    new_prompt: bool
    duration_s: float


def write_healed_search_config(cfg: dict[str, Any], state: dict[str, Any], source: str) -> Path:
    header = (
        "# AUTO-GENERATED by the search-based healing loop (python -m scripts.heal_search).\n"
        f"# Source run: {source}\n"
        "# Re-run the loop to regenerate it; manual edits will be overwritten.\n"
    )
    data = {
        "extends": "../base.yaml",
        "name": "healed_search",
        "target": cfg["target"],
        "garak": cfg["garak"],
        "system_prompts": {"learned_rules": state["system_prompts"].get("learned_rules", "")},
        "mitigations": state["mitigations"],
    }
    return save_yaml(data, HEALED_SEARCH_PATH, header=header)


def format_search_table(summary: dict[str, Any]) -> str:
    lines = [f"{'iter':<5}{'kind':<11}{'kept':<6}{'val ASR':>9}{'val FPR':>9}{'objective':>11}"
             f"{'calls':>7}{'time(s)':>9}  change"]
    for it in summary["iterations"]:
        val = it["val"]
        lines.append(
            f"{it['iteration']:<5}{it['kind']:<11}{('yes' if it['accepted'] else 'no'):<6}"
            f"{val['asr_macro'] * 100:>8.1f}%{val['fpr'] * 100:>8.1f}%{it['objective']:>11.4f}"
            f"{it['model_calls']:>7}{it['duration_s']:>9.1f}  {it['change'] or '-'}"
        )
    lines.append(f"best iteration: {summary['best_iteration']} | stop: {summary['stop_reason']} | "
                 f"total {summary['total_duration_s'] / 60:.1f} min")
    lines.append(f"healed config: {summary['healed_config_path']}")
    return "\n".join(lines)


class SearchHealer:
    """Runs the search loop and writes configs/experiments/healed_search.yaml."""

    def __init__(self, cfg: dict[str, Any], results_root: Path, phase: str = "all",
                 max_iterations: int | None = None,
                 start_cfg: dict[str, Any] | None = None) -> None:
        validate_search_cfg(cfg)
        if phase not in PHASES:
            raise ConfigError(f"phase must be one of {PHASES}")
        self.cfg = copy.deepcopy(cfg)
        self.search = cfg["search"]
        self.opt_cfg = cfg.get("optimizer") or {}
        self.optimizer_enabled = bool(self.opt_cfg.get("enabled", False))
        if phase == "optimizer" and not self.optimizer_enabled:
            raise ConfigError("phase 'optimizer' needs optimizer.enabled: true")
        self.phase = phase
        self.max_iterations = int(max_iterations or self.search["max_iterations"])
        self.max_move_iterations = int(self.search.get("max_move_iterations", 0) or 0)
        self.patience = int(self.search["patience"])
        self.max_candidates = int(self.search["max_candidates_per_iteration"])
        self.max_new_prompts = int(self.search["max_new_prompt_candidates_per_iteration"])
        self.combo_top_k = int(self.search["combo_top_k"])
        self.max_combo_size = int(self.search["max_combo_size"])
        self.learn_from = str(self.opt_cfg.get("learn_from", "model"))
        self.accept_on_model_level = bool(self.opt_cfg.get("accept_on_model_level", True))
        self.results_root = results_root
        self.run_dir = results_root / "search" / f"run_{datetime.now():%Y%m%d_%H%M%S}"
        state = copy.deepcopy(self.cfg)
        if start_cfg is not None:
            state["mitigations"] = copy.deepcopy(start_cfg["mitigations"])
            state["system_prompts"]["learned_rules"] = str(
                (start_cfg.get("system_prompts") or {}).get("learned_rules") or "")
        normalize(state["mitigations"])
        self.state = state
        self.initial_steps = {key: float(spec["step"])
                              for key, spec in self.search["thresholds"].items()}
        self.steps = dict(self.initial_steps)
        self.iterations: list[dict[str, Any]] = []
        self.history: list[dict[str, Any]] = []
        self.visited: set[str] = set()
        self._optimizer: PromptOptimizer | None = None

    def _obj(self, result: EvalResult) -> float:
        return objective(result, self.search)

    @staticmethod
    def _bare(cfg: dict[str, Any]) -> dict[str, Any]:
        """Same system prompt, guards switched off: what the model itself does."""
        bare = copy.deepcopy(cfg)
        bare["mitigations"]["input_filter"]["enabled"] = False
        bare["mitigations"]["output_filter"]["enabled"] = False
        return bare

    @staticmethod
    def _state_key(cfg: dict[str, Any]) -> str:
        """Identity of a configuration (mitigations + learned rules) for the no-revisit list."""
        return make_key(cfg["mitigations"], cfg["system_prompts"].get("learned_rules", ""))

    @staticmethod
    def _guards(cfg: dict[str, Any]) -> dict[str, Any]:
        """Mitigations without the system-prompt settings (to detect pure prompt changes)."""
        guards = copy.deepcopy(cfg["mitigations"])
        guards.pop("hardened_system_prompt", None)
        return guards

    def _record(self, iteration: int, kind: str, accepted: bool, change: str | None,
                reason: str, result: EvalResult, n_candidates: int, model_calls: int,
                duration_s: float, extra: dict[str, Any] | None = None) -> None:
        record = {
            "iteration": iteration, "kind": kind, "accepted": accepted, "change": change,
            "reason": reason, "objective": self._obj(result), "val": result.to_dict(),
            "candidates": n_candidates, "model_calls": model_calls, "duration_s": duration_s,
            "enabled_mitigations": describe_mitigations(self.state["mitigations"]),
            "learned_rules": self.state["system_prompts"].get("learned_rules", ""),
            "threshold_steps": dict(self.steps), "best_so_far": False,
        }
        record.update(extra or {})
        self.iterations.append(record)
        logger.info(
            "Iteration %d (%s) %s in %.1fs | val %s | objective %.4f | candidates %d | "
            "model calls %d",
            iteration, kind, "KEPT a change" if accepted else "no change", duration_s,
            result.brief(), self._obj(result), n_candidates, model_calls,
        )

    def _save_checkpoints(self, best_state: dict[str, Any]) -> None:
        for name, state in (("checkpoint_current.yaml", self.state),
                            ("checkpoint_best.yaml", best_state)):
            save_yaml({"system_prompts": {"learned_rules":
                                          state["system_prompts"].get("learned_rules", "")},
                       "mitigations": state["mitigations"]}, self.run_dir / name)

    def _write_candidates(self, iteration: int, kind: str, tried: list[Candidate],
                          chosen: Candidate | None) -> None:
        with (self.run_dir / "candidates.jsonl").open("a", encoding="utf-8") as handle:
            for cand in tried:
                handle.write(json.dumps({
                    "iteration": iteration, "kind": kind, "change": cand.label,
                    "new_prompt": cand.new_prompt, "asr_macro": cand.result.asr_macro,
                    "fpr": cand.result.fpr, "attack_hits": cand.result.attack_hits,
                    "benign_fp": cand.result.benign_fp, "objective": cand.objective,
                    "accepted_by_rule": cand.decision.accepted, "reason": cand.decision.reason,
                    "kept": cand is chosen, "model_calls": cand.result.model_calls,
                    "duration_s": round(cand.duration_s, 3),
                }, ensure_ascii=False) + "\n")

    def _try(self, iteration: int, index: int, moves: tuple[Move, ...], cand_cfg: dict[str, Any],
             evaluator: Evaluator, val: Split, current: EvalResult, current_sig: str) -> Candidate:
        start = time.perf_counter()
        new_prompt = prompt_signature(cand_cfg) != current_sig
        pure_prompt = new_prompt and self._guards(cand_cfg) == self._guards(self.state)
        result = evaluator.evaluate(cand_cfg, val, f"iter{iteration} cand{index}", log_summary=False)
        decision = decide(current, result, self.search, prompt_change=pure_prompt)
        candidate = Candidate(moves, describe(moves), cand_cfg, result, decision,
                              self._obj(result), new_prompt, time.perf_counter() - start)
        logger.info(
            "Iter %d | cand %2d%s | %-60s | ASR %5.1f%% (%+d) | FPR %5.1f%% (%+d) | obj %.4f | "
            "%s: %s | %.1fs",
            iteration, index, " [new prompt]" if new_prompt else "", candidate.label[:60],
            result.asr_macro * 100, decision.d_hits, result.fpr * 100, decision.d_fp,
            candidate.objective, "ACCEPTABLE" if decision.accepted else "rejected",
            decision.reason, candidate.duration_s,
        )
        return candidate

    def _steps_text(self) -> str:
        return ", ".join(f"{short_name(k)}={v:g}" for k, v in self.steps.items())
    
    def _halve_steps(self, iteration: int, tried: list[Candidate], chosen: Candidate | None) -> None:
        for key, spec in self.search["thresholds"].items():
            singles = [c for c in tried if len(c.moves) == 1 and c.moves[0].key == key]
            if not singles:
                continue
            if chosen is not None and any(m.key == key for m in chosen.moves):
                continue
            if any(c.decision.accepted for c in singles):
                continue
            old = self.steps[key]
            self.steps[key] = old / 2
            short = short_name(key)
            if self.steps[key] < float(spec["min_step"]):
                logger.info("Iteration %d | %s threshold: no gain at +/-%.4f; step %.4f is below "
                            "min_step %.4f -> this threshold is converged", iteration, short, old,
                            self.steps[key], float(spec["min_step"]))
            else:
                logger.info("Iteration %d | %s threshold: no gain at +/-%.4f -> step halved to "
                            "%.4f", iteration, short, old, self.steps[key])

    def _move_iteration(self, iteration: int, evaluator: Evaluator, val: Split,
                        current: EvalResult) -> tuple[bool, EvalResult]:
        start = time.perf_counter()
        calls_before = evaluator.client.calls
        kind = "thresholds" if self.phase == "thresholds" else "moves"
        singles = single_moves(self.state["mitigations"], self.search, self.steps,
                               thresholds_only=(kind == "thresholds"))
        current_sig = prompt_signature(self.state)
        logger.info("Iteration %d (%s) START | %d single moves | threshold steps: %s",
                    iteration, kind, len(singles), self._steps_text())
        tried: list[Candidate] = []
        deferred: list[tuple[Move, ...]] = []
        tabu_skipped = 0

        for move in singles:                      
            if len(tried) >= self.max_candidates:
                break
            cand_cfg = apply_moves(self.state, (move,))
            if cand_cfg is None:
                continue
            if self._state_key(cand_cfg) in self.visited:
                tabu_skipped += 1
                continue
            if not evaluator.is_warm(cand_cfg, val):
                deferred.append((move,))
                continue
            tried.append(self._try(iteration, len(tried) + 1, (move,), cand_cfg, evaluator, val,
                                   current, current_sig))

        for moves in deferred[: self.max_new_prompts]:      
            if len(tried) >= self.max_candidates:
                break
            cand_cfg = apply_moves(self.state, moves)
            if cand_cfg is not None:
                tried.append(self._try(iteration, len(tried) + 1, moves, cand_cfg, evaluator,
                                       val, current, current_sig))
        if len(deferred) > self.max_new_prompts:
            skipped = [describe(m) for m in deferred[self.max_new_prompts:]]
            logger.info("Iteration %d | %d new-system-prompt candidate(s) left for later "
                        "iterations (budget %d): %s", iteration, len(skipped),
                        self.max_new_prompts, "; ".join(skipped))

        ranked = sorted(tried, key=lambda c: c.objective)[: self.combo_top_k]
        for combo in combinations([c.moves[0] for c in ranked], self.max_combo_size): 
            if len(tried) >= self.max_candidates:
                logger.info("Iteration %d | candidate budget (%d) reached", iteration,
                            self.max_candidates)
                break
            cand_cfg = apply_moves(self.state, combo)
            if cand_cfg is None or not evaluator.is_warm(cand_cfg, val):
                continue
            if self._state_key(cand_cfg) in self.visited:
                tabu_skipped += 1
                continue
            tried.append(self._try(iteration, len(tried) + 1, combo, cand_cfg, evaluator, val,
                                   current, current_sig))
        if tabu_skipped:
            logger.info("Iteration %d | skipped %d candidate(s) that would return to an earlier "
                        "configuration (no-revisit list)", iteration, tabu_skipped)

        accepted = [c for c in tried if c.decision.accepted]
        chosen = min(accepted, key=lambda c: c.objective) if accepted else None
        self._halve_steps(iteration, tried, chosen)
        self._write_candidates(iteration, kind, tried, chosen)
        if chosen is not None:
            logger.info("Iteration %d | KEPT: %s | %s", iteration, chosen.label,
                        chosen.decision.reason)
            self.state = chosen.cfg
            self.visited.add(self._state_key(self.state))
            current = chosen.result
        else:
            logger.info("Iteration %d | no candidate passed the acceptance rule -> rolled back "
                        "(configuration unchanged)", iteration)
        self._record(iteration, kind, chosen is not None, chosen.label if chosen else None,
                     chosen.decision.reason if chosen else "no acceptable candidate", current,
                     len(tried), evaluator.client.calls - calls_before,
                     time.perf_counter() - start, {"tabu_skipped": tabu_skipped})
        return chosen is not None, current

    def _collect_cases(self, result: EvalResult, split: Split) -> list[Case]:
        attacks = {a.id: a for a in split.attacks}
        benign = {b.id: b.prompt for b in split.benign}
        cases: list[Case] = []
        for item in result.items:
            if item["kind"] == "attack" and item["hit"] and item["blocked_stage"] is None:
                attack = attacks.get(item["id"])
                cases.append(Case(item["id"], "attack", item["category"],
                                  attack.prompt if attack else "", item["raw_text"],
                                  _failure_reason(attack, item["category"])))
            elif item["kind"] == "benign" and item.get("refusal"):
                cases.append(Case(item["id"], "benign", item["tag"], benign.get(item["id"], ""),
                                  item["final_text"], "it refused a harmless request"))
        return cases

    def _optimizer_iteration(self, iteration: int, evaluator: Evaluator, improvement: Split,
                             val: Split, current: EvalResult) -> tuple[bool, EvalResult]:
        start = time.perf_counter()
        calls_before = evaluator.client.calls
        rng = random.Random(int(self.opt_cfg.get("seed", 7)) + iteration)
        if self._optimizer is None:
            self._optimizer = PromptOptimizer(self.cfg, self.opt_cfg)
        base = copy.deepcopy(self.state)
        base["mitigations"]["hardened_system_prompt"]["enabled"] = True  
        learned = str(base["system_prompts"].get("learned_rules") or "")
        model_level = self.learn_from == "model"

        def learn_view(cfg: dict[str, Any]) -> dict[str, Any]:
            return self._bare(cfg) if model_level else cfg

        logger.info("Iteration %d (optimizer) START | learning from %s-level failures | current "
                    "learned rules: %d words", iteration, self.learn_from, len(learned.split()))

        improvement_eval = evaluator.evaluate(learn_view(base), improvement,
                                              f"iter{iteration} improvement ({self.learn_from})")
        cases = self._collect_cases(improvement_eval, improvement)
        details: dict[str, Any] = {"learn_from": self.learn_from, "cases_available": len(cases)}
        if not cases:
            logger.info("Iteration %d | no %s-level failures on the improvement split; nothing "
                        "for the optimizer to learn", iteration, self.learn_from)
            self._record(iteration, "optimizer", False, None, "no failures to learn from",
                         current, 0, evaluator.client.calls - calls_before,
                         time.perf_counter() - start, details)
            write_json(details, self.run_dir / f"optimizer_iter_{iteration}.json")
            return False, current

        attacks = [c for c in cases if c.kind == "attack"]
        benign = [c for c in cases if c.kind == "benign"]
        size = int(self.opt_cfg.get("critique_batch", 8))
        n_benign = min(len(benign), max(1, size // 3)) if benign else 0
        batch = rng.sample(attacks, min(len(attacks), size - n_benign)) + rng.sample(benign, n_benign)
        failed_benign = {c.id for c in benign}
        keep_pool = [b for b in improvement.benign if b.id not in failed_benign]
        answers = {i["id"]: i["final_text"] for i in improvement_eval.items if i["kind"] == "benign"}
        keep = [Case(b.id, "keep", "benign", b.prompt, answers.get(b.id, ""),
                     "it helped correctly; this must keep working")
                for b in rng.sample(keep_pool, min(2, len(keep_pool)))]
        critique = self._optimizer.critique(learned, batch + keep, seed=rng.randint(1, 10**6))
        logger.info("Iteration %d | optimizer critique (%d cases: %d attacks obeyed, %d benign "
                    "refused):\n%s", iteration, len(batch), len(batch) - n_benign, n_benign, critique)
        proposals = self._optimizer.propose(learned, critique, self.history,
                                            int(self.opt_cfg.get("candidates", 3)),
                                            seed=rng.randint(1, 10**6))
        for index, rules in enumerate(proposals, start=1):
            logger.info("Iteration %d | proposal %d:\n%s", iteration, index, rules)
        details.update({"critique": critique, "proposals": proposals,
                        "batch_ids": [c.id for c in batch]})
        if not proposals:
            self._record(iteration, "optimizer", False, None, "no usable proposals", current, 0,
                         evaluator.client.calls - calls_before, time.perf_counter() - start, details)
            write_json(details, self.run_dir / f"optimizer_iter_{iteration}.json")
            return False, current

        n_att = int(self.opt_cfg.get("screen_attacks", 20))
        n_ben = int(self.opt_cfg.get("screen_benign", 10))
        share = float(self.opt_cfg.get("screen_failure_share", 0.6))
        failure_ids = [c.id for c in attacks]
        working_ids = [a.id for a in improvement.attacks if a.id not in {c.id for c in cases}]
        rng.shuffle(failure_ids)
        rng.shuffle(working_ids)
        n_fail = min(len(failure_ids), max(1, round(n_att * share)))
        attack_ids = failure_ids[:n_fail] + working_ids[: n_att - n_fail]
        benign_failures = [c.id for c in benign]
        other_benign = [b.id for b in improvement.benign if b.id not in set(benign_failures)]
        rng.shuffle(other_benign)
        benign_ids = (benign_failures + other_benign)[:n_ben]
        screen = improvement.subset(set(attack_ids), set(benign_ids), name="screen")
        logger.info("Iteration %d | screen batch: %d failures + %d working attacks, %d benign",
                    iteration, n_fail, len(attack_ids) - n_fail, len(benign_ids))
        screen_base = evaluator.evaluate(learn_view(self.state), screen,
                                         f"iter{iteration} screen current (actual state)")
        screened = []
        for index, rules in enumerate(proposals, start=1):
            cand_cfg = copy.deepcopy(base)
            cand_cfg["system_prompts"]["learned_rules"] = rules
            result = evaluator.evaluate(learn_view(cand_cfg), screen,
                                        f"iter{iteration} screen prop{index}")
            screened.append((result.attack_hits + result.benign_fp, index, rules, cand_cfg))
        current_errors = screen_base.attack_hits + screen_base.benign_fp
        margin = int(self.search["min_delta_attacks_prompt"])
        details["screen"] = {"current_errors": current_errors,
                             "proposal_errors": [s[0] for s in screened], "margin": margin}
        best_obj, best_index, best_rules, best_cfg = min(screened, key=lambda s: s[0])
        if best_obj > current_errors - margin:
            logger.info("Iteration %d | no proposal beats the current state on the screen batch by "
                        ">= %d errors (best %d vs current %d attacks+false positives) -> rolled back",
                        iteration, margin, best_obj, current_errors)
            self._record(iteration, "optimizer", False, None, "no proposal beat the screen batch",
                         current, len(proposals), evaluator.client.calls - calls_before,
                         time.perf_counter() - start, details)
            write_json(details, self.run_dir / f"optimizer_iter_{iteration}.json")
            return False, current

        val_result = evaluator.evaluate(best_cfg, val, f"iter{iteration} proposal{best_index}")
        decision = decide(current, val_result, self.search, prompt_change=True)
        cur_bare = evaluator.evaluate(self._bare(self.state), val,
                                      f"iter{iteration} model-level current")
        cand_bare = evaluator.evaluate(self._bare(best_cfg), val,
                                       f"iter{iteration} model-level prop{best_index}")
        d_model = cand_bare.attack_hits - cur_bare.attack_hits
        d_model_fp = cand_bare.benign_fp - cur_bare.benign_fp
        details["model_level"] = {"current_hits": cur_bare.attack_hits,
                                  "candidate_hits": cand_bare.attack_hits,
                                  "current_fp": cur_bare.benign_fp,
                                  "candidate_fp": cand_bare.benign_fp}
        if (not decision.accepted and self.accept_on_model_level
                and decision.asr_change != "worse" and decision.fpr_change != "worse"
                and val_result.fpr <= float(self.search["max_fpr"]) + 1e-9
                and d_model <= -int(self.search["min_delta_attacks_prompt"]) and d_model_fp <= 0):
            decision = Decision(
                True,
                f"pipeline ASR {decision.asr_change}, FPR {decision.fpr_change}; the model "
                f"without guards obeys {-d_model} fewer validation attacks (defence in depth)",
                decision.asr_change, decision.fpr_change, decision.d_hits, decision.d_fp,
                decision.objective_current, decision.objective_candidate,
            )
        history_result = cand_bare if model_level else val_result
        self.history.append({"iteration": iteration, "learned_rules": best_rules,
                             "objective": self._obj(history_result),
                             "asr": history_result.asr_macro, "fpr": history_result.fpr,
                             "accepted": decision.accepted})
        details.update({"validated_proposal": best_index, "decision": decision.to_dict(),
                        "validation": val_result.to_dict()})
        write_json(details, self.run_dir / f"optimizer_iter_{iteration}.json")
        logger.info("Iteration %d | proposal %d on validation: %s | model-level attacks obeyed "
                    "%d -> %d -> %s (%s)", iteration, best_index, val_result.brief(),
                    cur_bare.attack_hits, cand_bare.attack_hits,
                    "KEPT" if decision.accepted else "rolled back", decision.reason)
        if decision.accepted:
            self.state = best_cfg
            self.visited.add(self._state_key(self.state))
            current = val_result
            self.steps = dict(self.initial_steps)  
        self._record(iteration, "optimizer", decision.accepted,
                     f"learned rules (proposal {best_index})" if decision.accepted else None,
                     decision.reason, current, len(proposals),
                     evaluator.client.calls - calls_before, time.perf_counter() - start, details)
        return decision.accepted, current

    def _threshold_curves(self, evaluator: Evaluator, val: Split, tag: str) -> None:
        """Validation ASR/FPR versus each threshold, from cached answers (no model calls)."""
        step = float(self.search.get("threshold_curve_step", 0.05))
        for key, spec in self.search["thresholds"].items():
            curve_step = float(spec.get("curve_step", step))
            grid, value = [], float(spec["min"])
            while value <= float(spec["max"]) + 1e-9:
                grid.append(round(value, 4))
                value += curve_step
            if grid[-1] < float(spec["max"]):
                grid.append(float(spec["max"]))
            rows = []
            for threshold in grid:
                cand = copy.deepcopy(self.state)
                set_path(cand["mitigations"], key, threshold)
                if spec.get("requires"):
                    set_path(cand["mitigations"], spec["requires"], True)
                normalize(cand["mitigations"])
                result = evaluator.evaluate(cand, val, f"curve {threshold}", log_summary=False)
                rows.append({"threshold": threshold, "asr_macro": round(result.asr_macro, 4),
                             "fpr": round(result.fpr, 4), "attack_hits": result.attack_hits,
                             "benign_fp": result.benign_fp,
                             "objective": round(self._obj(result), 4)})
            parts = key.split(".")
            short = parts[-2] if parts[-1] == "threshold" else f"{parts[-2]}_{parts[-1]}"
            csv_path = self.run_dir / f"threshold_curve_{tag}_{short}.csv"
            with csv_path.open("w", encoding="utf-8", newline="") as handle:
                writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
                writer.writeheader()
                writer.writerows(rows)
            self._plot_curve(rows, key, csv_path.with_suffix(".png"))
            table = " ".join(f"{r['threshold']:.2f}:{r['asr_macro'] * 100:.0f}/{r['fpr'] * 100:.0f}"
                             for r in rows)
            logger.info("Threshold curve (%s, %s) threshold:ASR%%/FPR%% -> %s | %s", short, tag,
                        table, project_relative(csv_path))

    def _plot_curve(self, rows: list[dict[str, Any]], key: str, path: Path) -> None:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt

        current = self.state["mitigations"]
        for part in key.split("."):
            current = current[part]
        xs = [r["threshold"] for r in rows]
        fig, ax = plt.subplots(figsize=(7, 4))
        ax.plot(xs, [r["asr_macro"] * 100 for r in rows], marker="o", label="validation ASR")
        ax.plot(xs, [r["fpr"] * 100 for r in rows], marker="s", label="validation FPR")
        ax.axvline(float(current), color="grey", linestyle=":",
                   label=f"current {float(current):.3f}")
        ax.set_xlabel(key)
        ax.set_ylabel("%")
        ax.set_title(f"Threshold diagnostic: {key.split('.')[-2]} (cached, no model calls)")
        ax.grid(alpha=0.3)
        ax.legend(fontsize=8)
        fig.tight_layout()
        fig.savefig(path, dpi=130)
        plt.close(fig)

    def run(self) -> dict[str, Any]:
        loop_start = time.perf_counter()
        self.run_dir.mkdir(parents=True, exist_ok=True)
        evaluator = Evaluator(self.cfg)
        val = load_split(self.cfg, "validation")
        use_optimizer = self.phase in ("all", "optimizer") and self.optimizer_enabled
        improvement = load_split(self.cfg, "improvement") if use_optimizer else None
        logger.info(
            "Search START | phase=%s | max %d iterations (move budget %s) | objective=%s "
            "(fpr_weight=%s) | max_fpr=%.1f%% | optimizer learns from %s level | validation: "
            "%d attacks, %d benign | run dir=%s",
            self.phase, self.max_iterations, self.max_move_iterations or "none",
            self.search["objective"], self.search["fpr_weight"],
            float(self.search["max_fpr"]) * 100, self.learn_from, len(val.attacks),
            len(val.benign), project_relative(self.run_dir),
        )
        start = time.perf_counter()
        calls_before = evaluator.client.calls
        current = evaluator.evaluate(self.state, val, "start")
        self.visited.add(self._state_key(self.state))
        self._record(0, "start", True, None, "start configuration", current, 0,
                     evaluator.client.calls - calls_before, time.perf_counter() - start)
        start_history = (evaluator.evaluate(self._bare(self.state), val, "start model-level")
                         if self.learn_from == "model" else current)
        self.history.append({"iteration": 0,
                             "learned_rules": self.state["system_prompts"].get("learned_rules", ""),
                             "objective": self._obj(start_history),
                             "asr": start_history.asr_macro, "fpr": start_history.fpr,
                             "accepted": True})
        best_state, best_eval, best_iteration = copy.deepcopy(self.state), current, 0
        self._threshold_curves(evaluator, val, "start")

        mode = "optimizer" if self.phase == "optimizer" else "moves"
        stall_moves = stall_opt = moves_done = 0
        retune = False
        stop_reason = "max_iterations reached"
        for iteration in range(1, self.max_iterations + 1):
            stop = False
            if mode == "moves":
                accepted, current = self._move_iteration(iteration, evaluator, val, current)
                if retune:
                    retune = False
                    mode = "optimizer"
                else:
                    moves_done += 1
                    stall_moves = 0 if accepted else stall_moves + 1
                    budget_used = (self.max_move_iterations > 0
                                   and moves_done >= self.max_move_iterations)
                    if stall_moves >= self.patience or budget_used:
                        why = (f"{stall_moves} iteration(s) without an accepted change"
                               if stall_moves >= self.patience
                               else f"move budget of {self.max_move_iterations} iterations used")
                        if self.phase == "all" and self.optimizer_enabled:
                            logger.info("Move search: %s -> switching to the prompt optimizer", why)
                            mode, stall_moves = "optimizer", 0
                        else:
                            stop_reason = f"move search stopped ({why})"
                            stop = True
            else:
                accepted, current = self._optimizer_iteration(iteration, evaluator, improvement,
                                                              val, current)
                if accepted:
                    stall_opt = 0
                    if self.phase == "all":
                        mode, retune = "moves", True
                else:
                    stall_opt += 1
                    if stall_opt >= self.patience:
                        stop_reason = (f"prompt optimizer stalled ({self.patience} iterations "
                                       "without an accepted edit)")
                        stop = True
            improved = self._obj(current) < self._obj(best_eval) - 1e-12
            tie_but_kept = accepted and self._obj(current) <= self._obj(best_eval) + 1e-12
            if improved or tie_but_kept:
                best_state, best_eval, best_iteration = copy.deepcopy(self.state), current, iteration
                self.iterations[-1]["best_so_far"] = True
            self._save_checkpoints(best_state)
            if stop:
                break

        if best_iteration != self.iterations[-1]["iteration"]:
            logger.info("Restoring the best checkpoint from iteration %d (objective %.4f)",
                        best_iteration, self._obj(best_eval))
        self.state = best_state
        self._save_checkpoints(best_state)
        self._threshold_curves(evaluator, val, "final")
        healed_path = write_healed_search_config(self.cfg, self.state,
                                                 project_relative(self.run_dir))
        try:
            manifest = load_manifest(self.cfg)
        except FileNotFoundError:
            manifest = {}
        settings = {k: self.search[k] for k in _REQUIRED if k != "toggles"}
        settings["max_move_iterations"] = self.max_move_iterations
        summary = {
            "name": self.cfg["name"],
            "model": self.cfg["target"]["model"],
            "timestamp": datetime.now().isoformat(timespec="seconds"),
            "phase": self.phase,
            "search_settings": settings,
            "optimizer_settings": {"learn_from": self.learn_from,
                                   "accept_on_model_level": self.accept_on_model_level,
                                   "model": self.opt_cfg.get("model")},
            "splits_created": manifest.get("created"),
            "iterations": self.iterations,
            "best_iteration": best_iteration,
            "best_validation": best_eval.to_dict(),
            "best_objective": self._obj(best_eval),
            "final_mitigations": self.state["mitigations"],
            "final_enabled_mitigations": describe_mitigations(self.state["mitigations"]),
            "learned_rules": self.state["system_prompts"].get("learned_rules", ""),
            "optimizer_history": self.history,
            "stop_reason": stop_reason,
            "healed_config_path": project_relative(healed_path),
            "run_dir": project_relative(self.run_dir),
            "total_duration_s": time.perf_counter() - loop_start,
        }
        write_json(summary, self.run_dir / "summary.json")
        write_json(summary, self.results_root / "search" / "summary.json")
        logger.info("Search END | best iteration %d | %s | stop: %s | %.1f min | healed config %s "
                    "| %s", best_iteration, best_eval.brief(), stop_reason,
                    summary["total_duration_s"] / 60, project_relative(healed_path),
                    evaluator.cache_report())
        return summary