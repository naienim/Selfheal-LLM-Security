from __future__ import annotations

import copy
import logging
import time
from datetime import datetime
from pathlib import Path
from typing import Any

from selfheal.config import (
    PROJECT_ROOT,
    describe_mitigations,
    get_path,
    project_relative,
    save_yaml,
    set_path,
)
from selfheal.experiment import (
    load_summary_if_compatible,
    overall_asr,
    run_benign,
    run_scans,
    write_json,
)

logger = logging.getLogger(__name__)

HEALED_CONFIG_PATH = PROJECT_ROOT / "configs" / "experiments" / "healed.yaml"


def _strengthen(key: str, old: Any, new: Any) -> Any:
    if isinstance(old, bool) and isinstance(new, bool):
        return old or new
    old_num = isinstance(old, (int, float)) and not isinstance(old, bool)
    new_num = isinstance(new, (int, float)) and not isinstance(new, bool)
    if key.endswith("threshold") and old_num and new_num:
        return min(old, new)
    return new


def apply_step(mitigations: dict[str, Any], step: dict[str, Any]) -> dict[str, list[Any]]:
    """Apply one playbook step in place; return ``{key: [old, new]}`` for real changes."""
    changes: dict[str, list[Any]] = {}
    for key, value in (step.get("set") or {}).items():
        old = get_path(mitigations, key)
        new = value if old is None else _strengthen(key, old, value)
        if old != new:
            set_path(mitigations, key, new)
            changes[key] = [old, new]
    return changes


def write_healed_config(cfg: dict[str, Any], mitigations: dict[str, Any], source: str) -> Path:
    """Write configs/experiments/healed.yaml (the final self-healed configuration)."""
    header = (
        "# AUTO-GENERATED by the self-healing loop (python -m scripts.run_healing).\n"
        f"# Source run: {source}\n"
        "# Re-run the loop to regenerate it; manual edits will be overwritten.\n"
    )
    data = {
        "extends": "../base.yaml",
        "name": "healed",
        "target": cfg["target"],
        "garak": cfg["garak"],
        "mitigations": mitigations,
    }
    return save_yaml(data, HEALED_CONFIG_PATH, header=header)


class HealingLoop:
    """Iteratively patch failing categories until the target ASR or the iteration limit."""

    def __init__(
        self, cfg: dict[str, Any], results_root: Path, reuse_baseline: Path | None = None
    ) -> None:
        self.cfg = copy.deepcopy(cfg)
        self.healing = cfg["healing"]
        self.target = float(self.healing["target_asr"])
        self.max_iterations = int(self.healing["max_iterations"])
        self.max_fpr = float(self.healing.get("max_false_positive_rate", 0.10))
        self.rescan_only_failed = bool(self.healing.get("rescan_only_failed", True))
        self.playbook: dict[str, list[dict[str, Any]]] = self.healing.get("playbook", {})
        self.results_root = results_root
        self.reuse_baseline = reuse_baseline
        self.run_dir = results_root / "healing" / f"run_{datetime.now():%Y%m%d_%H%M%S}"
        self.categories = list(cfg["garak"]["categories"])
        self.levels = {category: 0 for category in self.categories}
        self.iterations: list[dict[str, Any]] = []

    def _record(
        self,
        index: int,
        label: str,
        accepted: bool,
        changes: list[dict[str, Any]],
        scanned: list[str],
        metrics: dict[str, dict[str, Any]],
        benign: dict[str, Any],
        mitigations: dict[str, Any],
        scan_s: float,
        benign_s: float,
        total_s: float,
    ) -> None:
        macro, micro = overall_asr(metrics)
        record = {
            "iteration": index,
            "label": label,
            "accepted": accepted,
            "changes": changes,
            "scanned_categories": scanned,
            "categories": {
                c: {
                    "asr": metrics[c]["asr"],
                    "fails": metrics[c]["fails"],
                    "total": metrics[c]["total"],
                    "carried_over": c not in scanned,
                    "duration_s": metrics[c].get("duration_s", 0.0) if c in scanned else 0.0,
                    "report_path": metrics[c].get("report_path"),
                }
                for c in self.categories
            },
            "overall_asr_macro": macro,
            "overall_asr_micro": micro,
            "benign_fpr": benign["fpr"],
            "benign_false_positives": benign["false_positives"],
            "benign_n": benign["n"],
            "enabled_mitigations": describe_mitigations(mitigations),
            "scan_duration_s": scan_s,
            "benign_duration_s": benign_s,
            "duration_s": total_s,
        }
        self.iterations.append(record)
        per_category = " | ".join(
            f"{c}={metrics[c]['asr'] * 100:.1f}%{'*' if c not in scanned else ''}"
            for c in self.categories
        )
        logger.info(
            "Iteration %d (%s) finished in %.1fs [scan %.1fs, benign %.1fs] | %s | "
            "overall=%.1f%% | benign FPR=%.1f%%  (* = carried over, not re-scanned)",
            index,
            label,
            total_s,
            scan_s,
            benign_s,
            per_category,
            macro * 100,
            benign["fpr"] * 100,
        )

    def _baseline(self, state: dict[str, Any]) -> tuple[dict[str, Any], dict[str, Any]]:
        start = time.perf_counter()
        reused = (
            load_summary_if_compatible(self.reuse_baseline, state) if self.reuse_baseline else None
        )
        if reused is not None:
            logger.info("Iteration 0: reusing baseline results from %s", self.reuse_baseline)
            metrics, benign = reused["categories"], reused["benign"]
            self._record(0, "baseline probe (reused)", True, [], [], metrics, benign,
                         state["mitigations"], 0.0, 0.0, time.perf_counter() - start)
            return metrics, benign
        logger.info("Iteration 0: baseline probe of all categories")
        scan_start = time.perf_counter()
        metrics = run_scans(state, self.run_dir / "iter_0", label="heal_iter0")
        scan_s = time.perf_counter() - scan_start
        benign_start = time.perf_counter()
        benign = run_benign(state, out_path=self.run_dir / "iter_0" / "benign_results.json")
        benign_s = time.perf_counter() - benign_start
        self._record(0, "baseline probe", True, [], list(self.categories), metrics, benign,
                     state["mitigations"], scan_s, benign_s, time.perf_counter() - start)
        return metrics, benign

    def _plan_patch(
        self, iteration: int, failing: list[str], metrics: dict[str, dict[str, Any]],
        mitigations: dict[str, Any], levels: dict[str, int],
    ) -> list[dict[str, Any]]:
        """Apply the next playbook step of every failing category (in place)."""
        changes: list[dict[str, Any]] = []
        for category in failing:
            steps = self.playbook.get(category, [])
            level = levels[category]
            if level >= len(steps):
                logger.warning(
                    "Iteration %d | %s still fails (ASR=%.1f%%) but its playbook is exhausted",
                    iteration, category, metrics[category]["asr"] * 100,
                )
                continue
            step = steps[level]
            diff = apply_step(mitigations, step)
            levels[category] = level + 1
            reason = (
                f"{category} ASR {metrics[category]['asr']:.1%} > target {self.target:.1%}"
            )
            logger.info(
                "Iteration %d | %s -> applying step %d/%d: %s",
                iteration, reason, level + 1, len(steps), step.get("description", ""),
            )
            for key, (old, new) in diff.items():
                logger.info("Iteration %d |   changed %s: %r -> %r", iteration, key, old, new)
            if not diff:
                logger.info("Iteration %d |   no new settings (already enabled by another fix)",
                            iteration)
            changes.append(
                {
                    "category": category,
                    "step": level + 1,
                    "description": step.get("description", ""),
                    "reason": reason,
                    "diff": diff,
                }
            )
        return changes

    def run(self) -> dict[str, Any]:
        """Execute the loop and return the healing summary."""
        loop_start = time.perf_counter()
        self.run_dir.mkdir(parents=True, exist_ok=True)
        state = copy.deepcopy(self.cfg)
        logger.info(
            "Healing START | target ASR <= %.1f%% per category | max %d iterations | "
            "max benign FPR %.1f%% | rescan_only_failed=%s",
            self.target * 100, self.max_iterations, self.max_fpr * 100, self.rescan_only_failed,
        )
        metrics, benign = self._baseline(state)
        stop_reason = ""
        for iteration in range(1, self.max_iterations + 1):
            failing = [c for c in self.categories if metrics[c]["asr"] > self.target]
            if not failing:
                stop_reason = "target ASR reached for every category"
                break
            iter_start = time.perf_counter()
            candidate = copy.deepcopy(state["mitigations"])
            new_levels = dict(self.levels)
            changes = self._plan_patch(iteration, failing, metrics, candidate, new_levels)
            if not changes:
                stop_reason = "playbook exhausted for every failing category"
                break

            trial = copy.deepcopy(state)
            trial["mitigations"] = candidate
            iter_dir = self.run_dir / f"iter_{iteration}"
            benign_start = time.perf_counter()
            trial_benign = run_benign(trial, out_path=iter_dir / "benign_results.json")
            benign_s = time.perf_counter() - benign_start
            if trial_benign["fpr"] > self.max_fpr:
                logger.warning(
                    "Iteration %d REJECTED | benign FPR %.1f%% exceeds limit %.1f%% | "
                    "reverting %d change(s) and stopping",
                    iteration, trial_benign["fpr"] * 100, self.max_fpr * 100, len(changes),
                )
                self._record(iteration, "rejected: false-positive limit", False, changes, [],
                             metrics, trial_benign, candidate, 0.0, benign_s,
                             time.perf_counter() - iter_start)
                stop_reason = "stopped: next patch exceeded the false-positive limit"
                break

            state, self.levels, benign = trial, new_levels, trial_benign
            to_scan = failing if self.rescan_only_failed else list(self.categories)
            scan_start = time.perf_counter()
            metrics = {**metrics, **run_scans(state, iter_dir, to_scan, f"heal_iter{iteration}")}
            scan_s = time.perf_counter() - scan_start
            self._record(iteration, "patch + verify", True, changes, to_scan, metrics, benign,
                         state["mitigations"], scan_s, benign_s, time.perf_counter() - iter_start)
        else:
            still_failing = [c for c in self.categories if metrics[c]["asr"] > self.target]
            stop_reason = (
                "max_iterations reached; still failing: " + ", ".join(still_failing)
                if still_failing
                else "target ASR reached for every category"
            )

        converged = all(metrics[c]["asr"] <= self.target for c in self.categories)
        healed_path = write_healed_config(
            self.cfg, state["mitigations"], project_relative(self.run_dir)
        )
        summary = {
            "name": self.cfg["name"],
            "model": self.cfg["target"]["model"],
            "timestamp": datetime.now().isoformat(timespec="seconds"),
            "target_asr": self.target,
            "max_iterations": self.max_iterations,
            "max_false_positive_rate": self.max_fpr,
            "rescan_only_failed": self.rescan_only_failed,
            "converged": converged,
            "stop_reason": stop_reason,
            "iterations": self.iterations,
            "final_mitigations": state["mitigations"],
            "final_enabled_mitigations": describe_mitigations(state["mitigations"]),
            "healed_config_path": project_relative(healed_path),
            "run_dir": project_relative(self.run_dir),
            "total_duration_s": time.perf_counter() - loop_start,
        }
        write_json(summary, self.run_dir / "healing_summary.json")
        write_json(summary, self.results_root / "healing" / "summary.json")
        logger.info(
            "Healing END | converged=%s | reason: %s | %d iteration record(s) | %.1fs | "
            "healed config written to %s",
            converged, stop_reason, len(self.iterations), summary["total_duration_s"],
            project_relative(healed_path),
        )
        return summary